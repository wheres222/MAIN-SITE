export const DICTIONARIES: Record<string, Dictionary> = {
  en,
  de,
  ru,
  es,
  fr,
  pt,
  pl,
  tr,
};

/**
 * Look up a key, falling back to English and finally to the key itself.
 *
 * `vars` does simple {name} interpolation — enough for the one or two strings
 * that need a value embedded, without pulling in an ICU message formatter for
 * a chrome-only dictionary.
 */
export function translate(
  locale: string,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = DICTIONARIES[locale] ?? {};
  let value: string = dict[key] ?? en[key] ?? key;

  if (vars) {
    for (const [name, v] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${name}\\}`, "g"), String(v));
    }
  }
  return value;
}
